// Generates minimal, valid, on-brand solid-color PNG placeholders for the
// metadata-level images (OG preview, apple-touch-icon) that browsers/crawlers
// fetch directly rather than through a React <Image>/LazyImage component — so
// LazyImage's graceful-degradation fallback doesn't apply to them, and they
// need to actually exist as real files. Uses only Node's built-in zlib; no
// image-processing dependency. Real designed artwork can replace these later
// without any code changes, per Section 15.12.
import { deflateSync } from "node:zlib";
import { writeFileSync } from "node:fs";

function makeCrcTable() {
  const table = [];
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[n] = c >>> 0;
  }
  return table;
}
const CRC_TABLE = makeCrcTable();

function crc32(buf) {
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    crc = CRC_TABLE[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const typeBuf = Buffer.from(type, "ascii");
  const lenBuf = Buffer.alloc(4);
  lenBuf.writeUInt32BE(data.length, 0);
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([lenBuf, typeBuf, data, crcBuf]);
}

function solidColorPng(width, height, [r, g, b]) {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

  const ihdrData = Buffer.alloc(13);
  ihdrData.writeUInt32BE(width, 0);
  ihdrData.writeUInt32BE(height, 4);
  ihdrData[8] = 8; // bit depth
  ihdrData[9] = 2; // color type: RGB
  ihdrData[10] = 0; // compression method
  ihdrData[11] = 0; // filter method
  ihdrData[12] = 0; // interlace method
  const ihdr = chunk("IHDR", ihdrData);

  const rowSize = 1 + width * 3;
  const raw = Buffer.alloc(rowSize * height);
  for (let y = 0; y < height; y++) {
    const rowStart = y * rowSize;
    raw[rowStart] = 0; // filter type: none
    for (let x = 0; x < width; x++) {
      const px = rowStart + 1 + x * 3;
      raw[px] = r;
      raw[px + 1] = g;
      raw[px + 2] = b;
    }
  }
  const idat = chunk("IDAT", deflateSync(raw));
  const iend = chunk("IEND", Buffer.alloc(0));

  return Buffer.concat([signature, ihdr, idat, iend]);
}

// #0A2E4D — the deepest stop of the Primary Gradient (Section 10).
const BRAND_NAVY = [0x0a, 0x2e, 0x4d];

writeFileSync("public/og-image.png", solidColorPng(1200, 630, BRAND_NAVY));
writeFileSync("public/apple-touch-icon.png", solidColorPng(180, 180, BRAND_NAVY));

console.log("Wrote public/og-image.png (1200x630) and public/apple-touch-icon.png (180x180)");
